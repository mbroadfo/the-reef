"""Replay Hunter over real (free, cached) history and print a markdown report.

Run:  uv run python tools/historical_replay.py [--write]
Needs the local cache from tools/fetch_history.py; makes no network calls. ``--write`` saves
docs/reef2-hunter-history.md (aggregate results only, never the vendor rows).
"""
from __future__ import annotations

import argparse
import statistics
from datetime import date
from decimal import Decimal
from pathlib import Path

from the_reef.backtest import cache
from the_reef.backtest.history import CachedCalendar, HistoricalBarSource
from the_reef.backtest.replay import WindowResult, run_window
from the_reef.backtest.universe import BENCHMARK, UNIVERSE
from the_reef.execution.costs import ExecutionCosts
from the_reef.market.calendar import ExchangeCalendar

D = Decimal
OUT = Path(__file__).resolve().parents[1] / "docs" / "reef2-hunter-history.md"

SCENARIOS = {
    "Frictionless": ExecutionCosts(),
    "Base": ExecutionCosts(D("5"), D("20"), D("0.005")),
    "Stress": ExecutionCosts(D("15"), D("75"), D("0.01")),
}
YEARS = list(range(2016, 2026))


def pct(x: Decimal, nd: int = 1) -> str:
    return f"{x * 100:+.{nd}f}%"


def windows(last_day: date) -> list[tuple[str, date, date]]:
    out = [(str(y), date(y, 1, 1), date(y, 12, 31)) for y in YEARS]
    out.append(("2026 YTD", date(2026, 1, 1), last_day))
    out.append((f"2016-{last_day.year} continuous", date(2016, 1, 1), last_day))
    return out


def first_session(cal, d: date) -> date:
    while cal.session(d) is None:
        d = date.fromordinal(d.toordinal() + 1)
    return d


def last_session(cal, d: date) -> date:
    while cal.session(d) is None:
        d = date.fromordinal(d.toordinal() - 1)
    return d


def table(rs: list[WindowResult]) -> list[str]:
    rows = ["| Window | Hunter sleeve | SPY | Univ. buy&hold | Hunter maxDD | SPY maxDD | Avg exposure | Round trips | Win rate | Stop exits | Turnover (x capital) | Paused |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for r in rs:
        wr = f"{r.wins / r.round_trips * 100:.0f}%" if r.round_trips else "-"
        se = f"{r.stop_exits / r.round_trips * 100:.0f}%" if r.round_trips else "-"
        rows.append(f"| {r.label} | {pct(r.sleeve_return)} | {pct(r.spy_return)} | {pct(r.basket_return)} | "
                    f"{pct(r.sleeve_max_dd)} | {pct(r.spy_max_dd)} | {r.avg_exposure * 100:.0f}% | {r.round_trips} | {wr} | {se} | "
                    f"{r.turnover:.1f} | {r.pause_share * 100:.0f}% |")
    return rows


def provenance_line(p) -> str:
    if not p.present:
        return "- Provenance: NO MANIFEST beside the cache, so the source and integrity of this data cannot be shown."
    src = p.source or {}
    when = (src.get("files_modified_between") or ["unknown"])[0][:10]
    return (f"- Provenance: private cache manifest present; {p.checked} files, every SHA-256 matches; manifest digest `{p.digest[:16]}`; "
            f"{src.get('provider', 'unknown source')} (yfinance {src.get('yfinance_version', '?')}); files written from {when}"
            + (f" ({src['note']})" if src.get("note") else "") + ".")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    prov = cache.verify_manifest()
    if prov.present and not prov.ok:
        raise SystemExit(f"cache does not match its manifest (altered {prov.altered}, missing {prov.missing}, unlisted {prov.unlisted}); refetch or investigate")
    cal = CachedCalendar(ExchangeCalendar())
    bars = HistoricalBarSource(cal, [*UNIVERSE, BENCHMARK])
    q = bars.quality
    last_day = max(x.last for x in q.per_symbol.values() if x.last)
    first_day = min(x.first for x in q.per_symbol.values() if x.first)
    wins = [(lbl, first_session(cal, a), last_session(cal, min(b, last_day))) for lbl, a, b in windows(last_day)]
    results: dict[str, list[WindowResult]] = {}
    for name, costs in SCENARIOS.items():
        results[name] = []
        for lbl, a, b in wins:
            r = run_window(f"{lbl}-{name}", cal, bars, a, b, costs)
            r.label = lbl
            results[name].append(r)
    base = results["Base"]
    L: list[str] = [
        "# Hunter on real historical prices (offline replay)", "",
        "> **Read this first.** This is a *fixed-universe, survivorship-biased* replay. It is **not** a survivorship-free "
        "historical simulation and it is **not evidence of an investment edge.** See Limitations.", "",
        f"Generated by `tools/historical_replay.py` from a local cache of free Yahoo Finance daily bars "
        f"({first_day} .. {last_day}). Aggregate results only; the vendor rows are never committed. Hunter v1 rules, "
        "D0 sleeve weight 40% ($4,000 of a $10,000 fund), the real Risk Engine and the same `advance()` loop as the synthetic "
        "walkthrough; each window is a fresh epoch. No LLM, no Atlas.", "",
        "Returns are **price returns** on the sleeve's funded capital ($4,000); dividends are excluded for Hunter, SPY and the "
        "basket alike. SPY is bought at the first session's open with whole shares and held. *Univ. buy&hold* is an "
        "equal-dollar basket of the same survivor universe: a yardstick for how much the universe itself flatters a "
        "long-only strategy, not a tradable benchmark.", ""]
    for name, costs in SCENARIOS.items():
        desc = ("No slippage and no fees: fills at the open print or the stop price." if name == "Frictionless" else
                f"Slippage {costs.slippage_bps} bps each side, an extra {costs.gap_slippage_bps} bps when a stop gaps through "
                f"at the open, fee ${costs.fee_per_share}/share.")
        L += [f"## {name} execution", "", desc, ""] + table(results[name]) + [""]
    L += ["**Paused** = share of sessions the fund sat 10%+ below its high-water mark, where the Risk Engine blocks new entries until a "
          "human resumes (provisional limit). The replay has no human, so in the continuous run the pause never lifts and Hunter "
          "stops trading for years; that, not strategy behaviour, explains its low exposure there. The single-year windows restart "
          "each epoch at a fresh high-water mark and are the fairer read.", ""]
    L += ["## Across the ten calendar years 2016-2025", "",
          "| Execution | Median Hunter | Median SPY | Years Hunter > SPY | Worst year Hunter | Worst year SPY | Median round trips | Median exposure |",
          "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for n, rs in results.items():
        ys = [r for r in rs if r.label in map(str, YEARS)]
        L.append(f"| {n} | {pct(statistics.median(r.sleeve_return for r in ys))} | {pct(statistics.median(r.spy_return for r in ys))} | "
                 f"{sum(1 for r in ys if r.sleeve_return > r.spy_return)}/{len(ys)} | {pct(min(r.sleeve_return for r in ys))} | "
                 f"{pct(min(r.spy_return for r in ys))} | {statistics.median(r.round_trips for r in ys):.0f} | "
                 f"{statistics.median(r.avg_exposure for r in ys) * 100:.0f}% |")
    L += ["", "Hunter's sleeve is only 40% of the fund, so fund-level figures are diluted by 60% idle cash; compare the sleeve to SPY "
          "(both on the same $4,000), not the fund.", ""]
    late = ", ".join(s for s, x in sorted(q.per_symbol.items()) if x.first and x.first > date(2015, 1, 5)) or "none"
    L += ["## Data quality", "",
          f"- Symbols: {len(q.per_symbol)} (universe {len(UNIVERSE)} + {BENCHMARK}); rows: {q.total('rows'):,}.",
          f"- Rows dropped as not on an NYSE session: {q.total('dropped_not_session')}; dropped for inconsistent OHLC: {q.total('dropped_bad_ohlc')}.",
          f"- Missing observations (sessions inside a symbol's own date range that no row covers): {q.total('missing_sessions')}; "
          f"longest gap: {max(x.max_gap_sessions for x in q.per_symbol.values())} sessions.",
          f"- Duplicate dates (extra rows for a date already seen, first kept): {q.total('duplicate_dates')}; "
          f"of those, repeats that disagreed with the first: {q.total('conflicting_duplicates')}.",
          provenance_line(prov),
          f"- Splits in the sample: {q.total('splits')}; dividends: {q.total('dividends')} (not credited).",
          f"- Symbols whose data starts after the cache start: {late}.",
          f"- Sessions with an unmarked holding (no official close), base run: {sum(r.unmarked_sessions for r in base)}.", ""]
    L += ["## Limitations (these change how to read every number above)", "",
          "1. **Survivorship bias.** The universe is a fixed list of large US companies that are listed *today*. Names that were "
          "delisted, acquired, bankrupt or dropped from the large-cap set during 2016-2026 are absent, and the free source does "
          "not carry them. Every long-only result is biased upward by an unknown amount. The *Univ. buy&hold* column shows how "
          "flattering the universe is to a passive holder; it is not a measurement of Hunter's own bias.",
          "2. **Selection hindsight.** Choosing today's large caps for 2016 includes winners nobody could have picked then, and "
          "sectors are today's classification applied to all history.",
          "3. **Corporate actions.** Prices are split-adjusted to today's share counts, so historical share counts and whole-share "
          "rounding differ from what could have been traded then. Dividends are not credited (this understates SPY and the basket "
          "more than Hunter, which holds briefly). Mergers, spin-offs and cash acquisitions of held names cannot occur because "
          "only survivors are present; the engine's cash-out path is untested on real data.",
          "4. **Execution.** Fills are at the daily open or the stop price plus the stated frictions. Daily bars cannot show whether "
          "a stop was hit before or after another intraday event, book depth, or halts. Real opening gaps in volatile names can be "
          "worse than the stress case.",
          "5. **Free data quality.** Yahoo data is unaudited and may be revised; the cache is a snapshot. Its terms do not allow "
          "redistribution, so this report publishes aggregates only and the replay cannot run in CI.",
          "6. **Statistics.** Ten annual windows of one strategy with hand-picked parameters. There is no out-of-sample test and no "
          "parameter search was run. Nothing here supports a claim of edge.", ""]
    text = "\n".join(L)
    if args.write:
        OUT.write_text(text + "\n", encoding="utf-8")
        print(f"wrote {OUT}")
    else:
        print(text)


if __name__ == "__main__":
    main()
